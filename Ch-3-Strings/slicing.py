
#! Slicing:-

#?--> Slicing lets you access a part of a string
#?--> Syntax:-
#?            string[start : end]  ##end index is executed

#? Example:-
#?          str = "GulabJamun"  ##Gulab

str = "Manish"

print(str[0:5])
print(str[:6])
print(str[0:])
print(str[3:6])


